export { canSendMail } from './mail.settings.js';

let warned = false;

export type QueueEmailInput = {
  organizationId: string;
  kind: string;
  to: string;
  subject: string;
  html: string;
  text: string;
  relatedType?: string;
  relatedId?: string;
  replyTo?: string;
  inReplyTo?: string;
  messageId?: string; // pre-generated by callers that must store the id (record emails); otherwise one is created
};

// Never throws: email trouble must not fail the business action that triggered it.
// Returns false when nothing was queued (mail not configured, or the insert failed).
export async function queueEmail({
  organizationId,
  kind,
  to,
  subject,
  html,
  text,
  relatedType,
  relatedId,
  replyTo,
  inReplyTo,
  messageId,
}: QueueEmailInput): Promise<boolean> {
  if (!(await canSendMail(organizationId))) {
    if (!warned) {
      warned = true;
      logger.warn('No email sending set up (organization Gmail settings or SMTP_URL / MAIL_FROM): outgoing emails are skipped');
    }
    return false;
  }
  try {
    await db.insert(emailOutbox).values({
      organizationId,
      kind,
      toEmail: oneLine(to),
      subject: oneLine(subject),
      bodyHtml: html,
      bodyText: text,
      relatedType,
      relatedId,
      messageId: messageId ?? newMessageId(env.MAIL_FROM),
      replyTo: replyTo ? oneLine(replyTo) : undefined,
      inReplyTo: inReplyTo ? oneLine(inReplyTo) : undefined,
    });
    return true;
  } catch (err) {
    logger.error({ err, kind }, 'Failed to queue email');
    return false;
  }
}

// Of the given addresses, the ones that belong to an active user of the organization (case-insensitive).
export async function activeUserEmails(organizationId: string, emails: string[]) {
  if (emails.length === 0) return [];
  const lower = emails.map((e) => e.toLowerCase());
  const rows = await db
    .select({ email: users.email })
    .from(users)
    .where(and(eq(users.organizationId, organizationId), eq(users.isActive, true), inArray(sql`lower(${users.email})`, lower)));
  return rows.map((r) => r.email.toLowerCase());
}

class MailService {
  async sendInvoice({ organizationId, id, to }: { organizationId: string; id: string; to?: string }) {
    const invoice = await invoicesService.getById({ organizationId, id }); // 404 when not in this organization
    const [row] = await db
      .select({ email: contacts.email })
      .from(orders)
      .innerJoin(contacts, eq(contacts.id, orders.contactId))
      .where(and(eq(orders.organizationId, organizationId), eq(orders.id, invoice.orderId), isNull(contacts.deletedAt)));
    const contactEmail = row?.email ?? undefined;
    // An override may only be the invoice's own contact or a colleague, so the endpoint cannot mail invoices to arbitrary outsiders.
    if (to && to.toLowerCase() !== contactEmail?.toLowerCase() && (await activeUserEmails(organizationId, [to])).length === 0) {
      throw new BadRequestError('Recipient must be the invoice contact or a user of this organization', 'RECIPIENT_NOT_ALLOWED');
    }
    const recipient = to ?? contactEmail;
    if (!recipient) throw new BadRequestError('No recipient email for this invoice', 'NO_RECIPIENT');

    const mail = await emailTemplatesService.render(organizationId, 'invoice', invoiceVariables(invoice));
    const queued = await queueEmail({ organizationId, kind: 'invoice', to: recipient, ...mail, relatedType: 'invoice', relatedId: id });
    if (!queued) throw new Error('Failed to queue email');
  }

  // Customer-visible staff reply -> email to the ticket's contact, if it has an address.
  async queueTicketReply({
    organizationId,
    ticket,
    body,
  }: {
    organizationId: string;
    ticket: { id: string; contactId: string | null; ticketNumber: number; subject: string };
    body: string;
  }) {
    await this.queueTicketMail({ organizationId, ticket, key: 'ticket_reply', vars: { reply_body: body } });
  }

  // Acknowledgement for a ticket opened from an inbound email.
  async queueTicketReceived({
    organizationId,
    ticket,
  }: {
    organizationId: string;
    ticket: { id: string; contactId: string | null; ticketNumber: number; subject: string };
  }) {
    await this.queueTicketMail({ organizationId, ticket, key: 'ticket_received', vars: {} });
  }

  private async queueTicketMail({
    organizationId,
    ticket,
    key,
    vars,
  }: {
    organizationId: string;
    ticket: { id: string; contactId: string | null; ticketNumber: number; subject: string };
    key: 'ticket_reply' | 'ticket_received';
    vars: Record<string, string>;
  }) {
    try {
      if (!ticket.contactId) return;
      const [row] = await db
        .select({ email: contacts.email, firstName: contacts.firstName, lastName: contacts.lastName })
        .from(contacts)
        .where(and(eq(contacts.organizationId, organizationId), eq(contacts.id, ticket.contactId), isNull(contacts.deletedAt)));
      if (!row?.email) return;
      const mail = await emailTemplatesService.render(organizationId, key, {
        ticket_number: ticket.ticketNumber,
        subject: ticket.subject,
        customer_name: [row.firstName, row.lastName].filter(Boolean).join(' '),
        ...vars,
      });
      const token = await supportRepository.ensureReplyToken(organizationId, ticket.id);
      await queueEmail({
        organizationId,
        kind: key,
        to: row.email,
        ...mail,
        relatedType: 'ticket',
        relatedId: ticket.id,
        replyTo: plusAddress(await mailSettings.inboundAddress(organizationId), token),
        inReplyTo: await supportRepository.lastMessageId(organizationId, ticket.id),
      });
    } catch (err) {
      logger.error({ err, ticketId: ticket.id }, 'Failed to queue ticket email');
    }
  }
}

export const mailService = new MailService();
